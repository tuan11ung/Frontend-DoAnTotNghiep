function compile(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const input = path.join(dir, entry.name);
    if (entry.isDirectory()) compile(input);
    else if (input.endsWith('.ts') && !input.endsWith('.d.ts')) {
      const target = path.join(output, path.relative(path.join(root, 'src'), input).replace(/\.ts$/, '.js'));
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.writeFileSync(target, ts.transpileModule(fs.readFileSync(input, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText.replace(/require\("@\/src\/([^"\n]+)"\)/g, (_, module) => `require(${JSON.stringify(path.join(output, module))})`));
    }
  }
}
